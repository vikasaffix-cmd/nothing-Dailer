"""Generate the adaptive launcher icon: a dot-matrix handset with a red dot.

Writes ic_launcher_background.xml (plate + unlit grid), ic_launcher_foreground.xml
and ic_launcher_monochrome.xml (lit handset + red dot) into <res>/drawable.
Everything sits inside the adaptive-icon safe zone (a 66dp circle in the 108dp
canvas) so circular launcher masks don't clip the design.
"""
import math, sys

res = sys.argv[1]
N = 26                    # dots per side
SPAN = 44.0               # grid width in dp, centred in the 108dp canvas
X0 = (108 - SPAN) / 2     # 32dp
P = SPAN / (N - 1)        # dot pitch
R_LIT, R_DIM, R_RED = P * 0.40, P * 0.22, P * 0.95
RED = (N - 3, N - 3)      # inside the grid's bottom-right, still in the safe zone

def in_ellipse(x, y, cx, cy, rx, ry, a):
    c, s = math.cos(a), math.sin(a)
    u = (x - cx) * c + (y - cy) * s
    v = -(x - cx) * s + (y - cy) * c
    return (u * u) / (rx * rx) + (v * v) / (ry * ry) <= 1

def near_seg(x, y, ax, ay, bx, by, w):
    vx, vy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((x - ax) * vx + (y - ay) * vy) / (vx * vx + vy * vy)))
    px, py = ax + t * vx, ay + t * vy
    return (x - px) ** 2 + (y - py) ** 2 <= w * w

def lit(c, r):
    # Handset shape defined on a 0..21 canvas, shrunk to ~92% and centred.
    x = 10.5 + ((c / (N - 1)) * 21 - 10.5) / 0.92
    y = 10.5 + ((r / (N - 1)) * 21 - 10.5) / 0.92
    a = -0.55
    return (in_ellipse(x, y, 5.6, 5.4, 3.0, 4.4, a)
            or in_ellipse(x, y, 15.9, 16.2, 4.4, 3.0, a)
            or near_seg(x, y, 6.6, 9.2, 12.4, 15.2, 1.9))

def dot(cx, cy, r, color):
    return (f'    <path android:fillColor="{color}" android:pathData="M{cx:.2f},{cy:.2f}'
            f'm-{r:.2f},0a{r:.2f},{r:.2f} 0,1 0,{2*r:.2f},0a{r:.2f},{r:.2f} 0,1 0,-{2*r:.2f},0"/>')

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- {note} Generated by icon_gen.py; '
        'edit the generator, not this file. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n')

fg, bg = [], ['    <path android:fillColor="#FF141414" android:pathData="M0,0h108v108h-108z" />',
              # slightly lighter rounded "screen" behind the grid, like the reference plate
              f'    <path android:fillColor="#FF1C1C1C" android:pathData="M{X0-3:.1f},{X0-3+6:.1f}'
              f'a6,6 0,0 1,6,-6h{SPAN+6-12:.1f}a6,6 0,0 1,6,6v{SPAN+6-12:.1f}a6,6 0,0 1,-6,6'
              f'h-{SPAN+6-12:.1f}a6,6 0,0 1,-6,-6z" />']
for r in range(N):
    for c in range(N):
        cx, cy = X0 + c * P, X0 + r * P
        if (c, r) == RED:
            fg.append(dot(cx, cy, R_RED, "#FFE8232B"))
        elif lit(c, r):
            fg.append(dot(cx, cy, R_LIT, "#FFF2F2F2"))
        else:
            bg.append(dot(cx, cy, R_DIM, "#FF343434"))

def write(name, note, body):
    with open(f"{res}/drawable/{name}.xml", "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD.format(note=note) + "\n".join(body) + "\n</vector>\n")

write("ic_launcher_background", "Dark plate, screen panel and the unlit dots of the grid.", bg)
write("ic_launcher_foreground", "Lit dot-matrix handset and red dot (also the notification icon).", fg)
write("ic_launcher_monochrome", "Themed-icon layer: lit handset and red dot only.", fg)
print(f"lit+red: {len(fg)}  unlit: {len(bg) - 2}")
